# 协议变体 P2（诱导探针）：原协议不变，系统提示末尾追加“抓核心”的因果分析要求（取自《Causal AI》笔记第 6、7 节的模板，改写成报告写法）。
# 目的：检验 v3h2 是否“本来就会”围绕核心机制做因果分析；若会，P2 与原协议的同模型对照就是阶段 1 取方向的配对数据。
import json, sys
P2 = ("\n\n本次实验的分析要求（只影响 report_markdown 中致因分析与责任分析的写法，其余协议不变）：\n"
      "1. 先划定因果框架：用一两句话指出本案最核心的事故机制——哪一方的何种行为或何种条件，经过什么过程形成了这一碰撞形态——作为首要研判假设；与该机制无关的背景信息不展开。\n"
      "2. 致因分析以核心机制为主线：写明支持它的已知事实，以及能把它与其他可能解释区分开的一到两项关键证据；其他因素只写与核心机制有因果联系的，并标明是直接原因、促成因素还是背景条件。\n"
      "3. 对首要因素做必要性与常态性判断：按现有事实，若没有该行为或条件，这起事故是否仍可能发生；该行为是否违反规范或明显异常。证据不足时写成有条件的判断（若……则……），并点明会使结论翻转的关键假设。\n"
      "4. 责任分析围绕核心机制涉及的注意义务展开，不对各方平均罗列；不作最终责任认定，不编造速度、距离等数值。")
src, dst = sys.argv[1], sys.argv[2]; n = 0
with open(dst, "w", encoding="utf-8") as w:
    for l in open(src, encoding="utf-8"):
        r = json.loads(l)
        if r["split"] != "dev": continue
        m = [dict(x) for x in r["messages"]]; assert m[0]["role"] == "system"
        m[0]["content"] += P2; r["messages"] = m; r["id"] = "p2" + r["id"]; r["variant"] = "P2"
        w.write(json.dumps(r, ensure_ascii=False) + "\n"); n += 1
print(n, "->", dst)
